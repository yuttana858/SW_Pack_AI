#!/usr/bin/env python3
"""Generate corpus/INDEX.md: an inventory of every corpus file (for people and for the assistant)."""
import re
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CORPUS = ROOT / "corpus"
rows, conf, total_sections, total_sources, total_verify, total_lines = [], Counter(), 0, 0, 0, 0
for p in sorted(CORPUS.rglob("*.md")):
    if p.name in ("README.md", "INDEX.md"):
        continue
    text = p.read_text(encoding="utf-8")
    end = text.find("\n---", 3)
    fm, body = yaml.safe_load(text[3:end]), text[end + 4:]
    secs = len(re.findall(r"^## ", body, re.M))
    srcs = len(fm.get("sources") or [])
    ver = body.count("VERIFY")
    lines = body.count("\n")
    conf[fm["confidence"]] += 1
    total_sections += secs; total_sources += srcs; total_verify += ver; total_lines += lines
    rows.append((p.relative_to(CORPUS), fm["id"], fm["title"], fm["confidence"], fm["status"], secs, srcs, ver, lines))

out = ["# Corpus index", "",
       "Generated by `tools/corpus_index.py`; do not edit. Each `##` section is one retrieval chunk.", "",
       f"**{len(rows)} files · {total_sections} sections · {total_sources} cited sources · {total_lines:,} lines · "
       f"{total_verify} VERIFY markers.** Confidence: " + ", ".join(f"{k} {v}" for k, v in conf.most_common()) + ".", "",
       "| File | Id | Title | Confidence | Status | Sections | Sources | VERIFY | Lines |",
       "|---|---|---|---|---|---|---|---|---|"]
out += [f"| `{f}` | `{i}` | {t} | {c} | {s} | {n} | {so} | {v} | {l} |" for f, i, t, c, s, n, so, v, l in rows]
(CORPUS / "INDEX.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(out[4:6]))
