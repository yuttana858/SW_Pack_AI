#!/usr/bin/env python3
"""Collect every VERIFY / SOURCE PENDING marker in corpus/ and data/ into docs/REVIEW-QUEUE.md."""
import re, sys
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else "corpus")
out = Path(sys.argv[2] if len(sys.argv) > 2 else "docs/REVIEW-QUEUE.md")
pat = re.compile(r"VERIFY|SOURCE PENDING|hypothetical", re.I)
rows, total = [], 0
files = sorted(root.rglob("*.md")) + sorted((root.parent / "data").rglob("*.yaml"))
for p in files:
    if p.name == "README.md" or "_example" in p.parts:
        continue
    section, hits = "", []
    for n, line in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
        if line.startswith("#"):
            section = line.lstrip("# ").strip()
        if pat.search(line) and not line.lstrip().startswith(("tags:", "- id:")):
            text = re.sub(r"\s+", " ", line.strip().strip("|").strip())[:220].replace("|", "/")
            hits.append((n, section, text))
    if hits:
        total += len(hits)
        rows.append((p.relative_to(root.parent), hits))

lines = ["# Corpus review queue", "",
         "Generated by `tools/review_queue.py`; regenerate after edits. Each item is a value an engineer must",
         "confirm against the primary source or replace with house / supplier data in `corpus/company/`.",
         "When resolved, remove the VERIFY marker, update `status`/`reviewer`/`last_reviewed` in the file's front-matter.", "",
         f"**{total} items across {len(rows)} files.**", "",
         "| File | Items |", "|---|---|"]
lines += [f"| `{f}` | {len(h)} |" for f, h in sorted(rows, key=lambda r: -len(r[1]))]
for f, hits in rows:
    lines += ["", f"## {f}", "", "| Line | Section | Item |", "|---|---|---|"]
    lines += [f"| {n} | {s[:60]} | {t} |" for n, s, t in hits]
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{total} items across {len(rows)} files -> {out}")
